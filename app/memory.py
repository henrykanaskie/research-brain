"""Library memory for Research mode: vault/memory/.

    core.md      the library map. Generated by the app from the library (regions and their key notes,
                 topics, recently changed notes, reading queue, where the PDFs and fragments are).
                 Deterministic: the same library gives the same file. Regenerated when the library
                 changes (debounced) and kept under CORE_MAX_BYTES. Nobody but the app writes it.
    findings.md  short findings recorded during Research through the one write tool, remember().
                 Each entry has an id, a date, its sources ([[note-id]] p. N) and the label
                 "Added via AI". The agent can only append; the user can edit or delete any entry in
                 the Memory view. When the file grows past FINDINGS_MAX_BYTES the oldest entries are
                 rolled into a short summary at the end.
    agents/      reserved for per-agent memory (not used yet; see agents/README.md).

Everything written here goes through _write(): only these file names, only inside the memory
folder, atomically (temp file + rename), under a lock (a thread lock plus an flock on .lock).
Nothing in this module imports numpy or the embedding stack.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import os
import re
import secrets
import threading
import time
from pathlib import Path

try:
    import fcntl
except ImportError:  # pragma: no cover (Windows)
    fcntl = None

CORE_MAX_BYTES = 8 * 1024
FINDINGS_MAX_BYTES = int(os.environ.get("RB_FINDINGS_MAX_BYTES", str(24 * 1024)))
SUMMARY_MAX_LINES = 30
TEXT_MAX = 400
MAX_SOURCES = 6
LABEL = "Added via AI"
WRITABLE = ("core.md", "findings.md", "agents/README.md")

FINDINGS_HEAD = ("# Findings\n\n"
                 "Short findings recorded while researching your library. Each entry lists its sources. "
                 "Edit or delete entries in the app (Memory) or here; keep the `## f-...` lines.\n")
SUMMARY_HEAD = "## Earlier findings (summary)"
AGENTS_README = ("# Per-agent memory (not used yet)\n\n"
                 "This folder is reserved for a later idea: separate memory files for separate research "
                 "agents (`agents/<name>.md`). Nothing reads or writes here today.\n")


class MemoryError(ValueError):
    """A rejected memory write; the message says why, in plain words."""


# ---------------------------------------------------------------- validation (remember)
_FENCE_RE = re.compile(r"```|~~~")
_CODE_LINE_RE = re.compile(
    r"^\s*(def |class |import |from \S+ import |function\b|const |let |var |return\b|#include|#!|"
    r"public |private |static |void |int |SELECT |INSERT |UPDATE |DELETE |CREATE |for\s*\(|while\s*\(|if\s*\(|"
    r"\$ |>>> |sudo |pip |npm |git |curl |cd |rm |<\w+[^>]*>|</\w+>)", re.I)
_CODE_TAIL_RE = re.compile(r"[{};]\s*$|=>|->\s*\w+\(|\w+\([^)]*\)\s*[{;]|\b\w+\s*=\s*[\[{(\"']|\b\w+\.\w+\(")
_LONG_TOKEN_RE = re.compile(r"\S{41,}")
_HTML_RE = re.compile(r"</?[a-zA-Z][\w-]*(\s[^<>]*)?/?>")
_CODEY = set("{}[];<>=|`\\")


def check_text(text: str) -> str:
    """Plain prose only, at most TEXT_MAX characters. Returns the normalised text or raises."""
    if not isinstance(text, str):
        raise MemoryError("text must be a string")
    raw = text.strip()
    if not raw:
        raise MemoryError("text is empty")
    if len(raw) > TEXT_MAX:
        raise MemoryError(f"text is {len(raw)} characters; the limit is {TEXT_MAX}. Keep it to one or two sentences.")
    if _FENCE_RE.search(raw) or "`" in raw:
        raise MemoryError("memory holds plain prose only: no code or code formatting")
    for line in text.strip("\n").splitlines():
        if line.startswith(("    ", "\t")) and line.strip():
            raise MemoryError("memory holds plain prose only: an indented line looks like code")
    for line in raw.splitlines():
        if _CODE_LINE_RE.search(line) or _CODE_TAIL_RE.search(line):
            raise MemoryError("memory holds plain prose only: that line looks like code")
    if _HTML_RE.search(raw):
        raise MemoryError("memory holds plain prose only: no HTML or markup")
    if _LONG_TOKEN_RE.search(raw):
        raise MemoryError("memory holds plain prose only: it contains a long string that isn't prose")
    letters = sum(ch.isalpha() for ch in raw)
    codey = sum(ch in _CODEY for ch in raw)
    if letters < 0.6 * len(raw.replace(" ", "")) or codey > max(4, 0.06 * len(raw)):
        raise MemoryError("memory holds plain prose only: too many symbols for a sentence")
    if raw.lstrip().startswith(("#", "-", "*", ">", "|")):
        raise MemoryError("memory holds plain prose only: no headings, lists, quotes or tables")
    return re.sub(r"\s+", " ", raw)


_SRC_RE = re.compile(r"^\s*\[{0,2}([a-z0-9][a-z0-9-]*)\]{0,2}\s*(?:(?:,|:|p\.?|page)\s*(\d{1,5}))?\s*$", re.I)


def parse_sources(sources) -> list[dict]:
    """[{id, page|None}] from ["id", "id p. 4", "[[id]] p. 4", {"id":..,"page":..}]. Shape only."""
    if isinstance(sources, (str, dict)):
        sources = [sources]
    if not isinstance(sources, (list, tuple)) or not sources:
        raise MemoryError("sources is required: the note ids (and pages) this finding comes from")
    out: list[dict] = []
    for s in sources:
        if isinstance(s, dict):
            nid, page = str(s.get("id") or "").strip(), s.get("page")
        else:
            m = _SRC_RE.match(str(s))
            if not m:
                raise MemoryError(f"couldn't read source {str(s)[:60]!r}; use a note id, optionally with a page")
            nid, page = m.group(1).lower(), m.group(2)
        if page in ("", None):
            page = None
        else:
            try:
                page = int(page)
            except (TypeError, ValueError):
                raise MemoryError(f"page for {nid} must be a number")
            if not 1 <= page <= 99999:
                raise MemoryError(f"page {page} for {nid} is out of range")
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", nid):
            raise MemoryError(f"{nid[:60]!r} isn't a note id")
        if {"id": nid, "page": page} not in out:
            out.append({"id": nid, "page": page})
    if len(out) > MAX_SOURCES:
        raise MemoryError(f"at most {MAX_SOURCES} sources")
    return out


def fmt_sources(sources: list[dict]) -> str:
    return "; ".join(f"[[{s['id']}]]" + (f" p. {s['page']}" if s.get("page") else "") for s in sources)


# ---------------------------------------------------------------- findings file format
_ENTRY_RE = re.compile(r"^## (f-[0-9a-z]{8,16})\s*$", re.M)
_ENTRY_ID_RE = re.compile(r"f-[0-9a-z]{8,16}")


def parse_findings(raw: str) -> tuple[list[dict], list[str]]:
    """(entries oldest first, summary lines). Entry: {id, date, label, sources, text, edited}."""
    summary: list[str] = []
    si = raw.find(SUMMARY_HEAD)
    body = raw
    if si != -1:
        body, tail = raw[:si], raw[si + len(SUMMARY_HEAD):]
        summary = [l[2:].strip() for l in tail.splitlines() if l.startswith("- ")]
    marks = list(_ENTRY_RE.finditer(body))
    entries = []
    for i, m in enumerate(marks):
        chunk = body[m.end():marks[i + 1].start() if i + 1 < len(marks) else len(body)]
        e = {"id": m.group(1), "date": "", "label": LABEL, "sources": [], "text": "", "edited": ""}
        text_lines = []
        for line in chunk.strip("\n").splitlines():
            kv = re.match(r"^- (date|label|sources|edited): ?(.*)$", line)
            if kv and not text_lines:
                k, v = kv.group(1), kv.group(2).strip()
                if k == "sources":
                    try:
                        e["sources"] = parse_sources([x for x in v.split(";") if x.strip()]) if v else []
                    except MemoryError:
                        e["sources"] = []
                else:
                    e[k] = v
            else:
                text_lines.append(line)
        e["text"] = "\n".join(text_lines).strip()
        entries.append(e)
    return entries, summary


def dump_findings(entries: list[dict], summary: list[str]) -> str:
    parts = [FINDINGS_HEAD]
    for e in entries:
        meta = [f"- date: {e['date']}", f"- label: {e.get('label') or LABEL}", f"- sources: {fmt_sources(e['sources'])}"]
        if e.get("edited"):
            meta.append(f"- edited: {e['edited']}")
        parts.append(f"## {e['id']}\n" + "\n".join(meta) + f"\n{e['text'].strip()}\n")
    if summary:
        parts.append(SUMMARY_HEAD + "\n" + "\n".join(f"- {s}" for s in summary[-SUMMARY_MAX_LINES:]) + "\n")
    return "\n".join(parts)


def _short(text: str, n: int) -> str:
    text = re.sub(r"\s+", " ", text or "").strip()
    return text if len(text) <= n else text[:n - 1].rsplit(" ", 1)[0] + "…"


# ---------------------------------------------------------------- the store
class Memory:
    def __init__(self, root: Path, note_exists=None, page_count=None):
        """root = vault/memory. note_exists(id) -> bool; page_count(id) -> int|None (pages of a
        paper's text, None when unknown) are used to validate sources."""
        self.root = Path(root)
        self.note_exists = note_exists or (lambda nid: True)
        self.page_count = page_count or (lambda nid: None)
        self._lock = threading.RLock()
        self._core_key = None
        self._core_dirty_at = 0.0
        self._thread = None
        self._stop = threading.Event()
        self.ensure_layout()

    # ---- files
    def ensure_layout(self) -> None:
        (self.root / "agents").mkdir(parents=True, exist_ok=True)
        if not (self.root / "agents" / "README.md").exists():
            self._write("agents/README.md", AGENTS_README)
        if not (self.root / "findings.md").exists():
            self._write("findings.md", dump_findings([], []))

    def _path(self, name: str) -> Path:
        if name not in WRITABLE:
            raise MemoryError(f"{name} isn't a memory file")
        p = (self.root / name).resolve()
        if self.root.resolve() not in p.parents:
            raise MemoryError("memory writes stay inside vault/memory")
        return p

    def _write(self, name: str, text: str) -> None:
        p = self._path(name)
        with self._locked():
            p.parent.mkdir(parents=True, exist_ok=True)
            tmp = p.with_name(f".{p.name}.{secrets.token_hex(4)}.tmp")
            with open(tmp, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
                f.flush()
                os.fsync(f.fileno())
            os.replace(tmp, p)

    def _locked(self):
        mem = self

        class _L:
            def __enter__(self):
                mem._lock.acquire()
                self.fh = None
                mem._depth = getattr(mem, "_depth", 0) + 1
                if fcntl is not None and mem._depth == 1:  # flock isn't reentrant across open() calls
                    try:
                        mem.root.mkdir(parents=True, exist_ok=True)
                        self.fh = open(mem.root / ".lock", "a")
                        fcntl.flock(self.fh, fcntl.LOCK_EX)
                    except OSError:
                        self.fh = None
                return self

            def __exit__(self, *a):
                mem._depth -= 1
                if self.fh is not None:
                    try:
                        fcntl.flock(self.fh, fcntl.LOCK_UN)
                    finally:
                        self.fh.close()
                mem._lock.release()
        return _L()

    def read(self, name: str) -> str:
        try:
            return self._path(name).read_text(encoding="utf-8")
        except OSError:
            return ""

    # ---- findings
    def findings(self) -> tuple[list[dict], list[str]]:
        return parse_findings(self.read("findings.md"))

    def _validate_sources(self, sources) -> list[dict]:
        srcs = parse_sources(sources)
        for s in srcs:
            if not self.note_exists(s["id"]):
                raise MemoryError(f"no note with id {s['id']!r} in the library")
            if s["page"]:
                n = self.page_count(s["id"])
                if n is not None and s["page"] > n:
                    raise MemoryError(f"{s['id']} has {n} pages, so p. {s['page']} doesn't exist")
        return srcs

    def remember(self, text: str, sources) -> dict:
        """The agent's one write: append a finding. Validates everything first."""
        clean = check_text(text)
        srcs = self._validate_sources(sources)
        try:  # private notes (app/privacy.py) never go into memory, which later goes to the AI
            from . import privacy
            priv = privacy.private_ids()
            leaked = privacy.copies_private(clean) if priv else []
        except Exception:
            priv, leaked = frozenset(), []
        if leaked or any(s["id"] in priv for s in srcs):
            raise MemoryError("that finding comes from a private note; private notes stay out of memory")
        with self._locked():
            entries, summary = self.findings()
            if any(_norm(e["text"]) == _norm(clean) for e in entries):
                raise MemoryError("that finding is already recorded")
            e = {"id": "f-" + secrets.token_hex(5), "date": dt.date.today().isoformat(), "label": LABEL,
                 "sources": srcs, "text": clean, "edited": ""}
            entries.append(e)
            entries, summary = self._roll(entries, summary)
            self._write("findings.md", dump_findings(entries, summary))
        return e

    def _roll(self, entries: list[dict], summary: list[str]) -> tuple[list[dict], list[str]]:
        """Over the size cap: fold the oldest entries into one-line summaries."""
        while len(entries) > 1 and len(dump_findings(entries, summary).encode()) > FINDINGS_MAX_BYTES:
            old = entries.pop(0)
            summary.append(f"{old['date'][:7]}: {_short(old['text'], 110)} ({fmt_sources(old['sources'][:2])})")
            summary = summary[-SUMMARY_MAX_LINES:]
        return entries, summary

    def edit_finding(self, entry_id: str, text: str | None = None, sources=None) -> dict:
        """The user's edit (from the Memory view). Same prose check, sources must still exist."""
        if not _ENTRY_ID_RE.fullmatch(entry_id or ""):
            raise KeyError(entry_id)
        with self._locked():
            entries, summary = self.findings()
            e = next((x for x in entries if x["id"] == entry_id), None)
            if e is None:
                raise KeyError(entry_id)
            if text is not None:
                e["text"] = check_text(text)
            if sources is not None:
                e["sources"] = self._validate_sources(sources)
            e["edited"] = dt.date.today().isoformat()
            self._write("findings.md", dump_findings(entries, summary))
            return e

    def delete_finding(self, entry_id: str) -> None:
        with self._locked():
            entries, summary = self.findings()
            keep = [x for x in entries if x["id"] != entry_id]
            if len(keep) == len(entries):
                raise KeyError(entry_id)
            self._write("findings.md", dump_findings(keep, summary))

    # ---- search (read-only tool)
    def search(self, query: str, limit: int = 10) -> list[dict]:
        """Lines of the map and findings that share the most words with the query."""
        words = {w for w in re.findall(r"[a-z0-9][a-z0-9_.\-]*", (query or "").lower()) if len(w) > 2}
        if not words:
            return []
        out = []
        for line in self.read("core.md").splitlines():
            if line.startswith("- ") or line.startswith("### "):
                low = line.lower()
                s = sum(1 for w in words if w in low)
                if s:
                    out.append({"score": s, "where": "map", "text": line.lstrip("-# ").strip()})
        entries, summary = self.findings()
        for e in entries:
            low = (e["text"] + " " + fmt_sources(e["sources"])).lower()
            s = sum(1 for w in words if w in low)
            if s:
                out.append({"score": s + 0.5, "where": "finding", "id": e["id"], "date": e["date"],
                            "text": e["text"], "sources": fmt_sources(e["sources"])})
        for line in summary:
            s = sum(1 for w in words if w in line.lower())
            if s:
                out.append({"score": s, "where": "earlier finding", "text": line})
        out.sort(key=lambda x: -x["score"])
        return out[:limit]

    # ---- core.md
    def refresh_core(self, key, build) -> bool:
        """Regenerate core.md if the library changed (key differs). build() -> markdown.
        Writes only when the content changed. Returns True when the file was rewritten."""
        if key == self._core_key and (self.root / "core.md").exists():
            return False
        text = build()
        self._core_key = key
        if text != self.read("core.md"):
            self._write("core.md", text)
            return True
        return False

    def start_watch(self, key_fn, build, interval: float = 2.0, debounce: float = 3.0) -> None:
        """Background regeneration: poll key_fn() every `interval` s; rebuild once it has been
        stable for `debounce` s (so a burst of edits or a big import costs one rebuild)."""
        if self._thread:
            return

        def loop():
            pending, since = None, 0.0
            while not self._stop.wait(interval):
                try:
                    k = key_fn()
                    if k == self._core_key:
                        pending = None
                        continue
                    if k != pending:
                        pending, since = k, time.monotonic()
                        continue
                    if time.monotonic() - since >= debounce:
                        self.refresh_core(k, build)
                        pending = None
                except Exception as e:  # never kill the thread
                    print(f"[research_brain] memory map refresh failed: {e!r}")
        self._thread = threading.Thread(target=loop, daemon=True, name="rb-memory")
        self._thread.start()

    def stop_watch(self) -> None:
        self._stop.set()


def _norm(s: str) -> str:
    return re.sub(r"\W+", " ", (s or "").lower()).strip()


# ---------------------------------------------------------------- the library map
def _importance(n: dict) -> float:
    return n.get("mass", 0) + 6 * n.get("opens", 0) + 4 * n.get("degree", 0) + (8 if n.get("has_pdf") else 0)


def _fmt_note(n: dict, frag_count: dict, title_len: int) -> str:
    bits = []
    if n.get("year"):
        bits.append(str(n["year"]))
    if n.get("has_pdf"):
        bits.append("PDF")
    if frag_count.get(n["id"]):
        bits.append(f"{frag_count[n['id']]} fragments")
    extra = f" ({', '.join(bits)})" if bits else ""
    return f"- [[{n['id']}]] {_short(n['title'], title_len)}{extra}"


def build_core(graph: dict, notes: list[dict], topics: dict | None = None, max_bytes: int = CORE_MAX_BYTES) -> str:
    """The library map as Markdown. graph = the /api/graph payload (nodes with cluster, mass, opens,
    degree, has_pdf; clusters with labels); notes = full notes (for updated/created dates).
    topics (optional) = {"topics": [{"name", "ids"}], "queue": [ids]}. Deterministic."""
    nodes = {n["id"]: n for n in graph.get("nodes", [])}
    full = {n["id"]: n for n in notes}
    tops = [n for n in nodes.values() if n["type"] != "fragment"]
    frag_count: dict[str, int] = {}
    for n in nodes.values():
        if n["type"] == "fragment" and n.get("parent"):
            frag_count[n["parent"]] = frag_count.get(n["parent"], 0) + 1
    papers = [n for n in tops if n["type"] == "paper"]
    with_pdf = [n for n in papers if n.get("has_pdf")]
    latest = max((full[i].get("updated") or "" for i in full), default="")[:10]
    rank = lambda xs: sorted(xs, key=lambda n: (-_importance(n), n["title"].lower(), n["id"]))

    def render(per_region: int, title_len: int, recent_n: int, extra_regions: bool) -> str:
        L = ["# Library map", "",
             "Generated by research_brain from your library; the app rewrites this file, so edits here are lost. "
             f"Last library change: {latest or 'none'}.",
             f"{len(papers)} papers ({len(with_pdf)} with PDFs), {len(tops) - len(papers)} notes, "
             f"{sum(frag_count.values())} fragments.", ""]
        clusters = sorted(graph.get("clusters", []), key=lambda c: (-c.get("size", 0), c.get("id", 0)))
        L.append("## Regions")
        shown_regions = clusters if extra_regions else clusters[:12]
        for c in shown_regions:
            members = rank([n for n in tops if n.get("cluster") == c["id"]])
            if not members:
                continue
            L.append(f"### {c.get('label') or 'Unnamed region'} ({len(members)} notes)")
            L += [_fmt_note(n, frag_count, title_len) for n in members[:per_region]]
            if len(members) > per_region:
                L.append(f"- and {len(members) - per_region} more")
        if len(clusters) > len(shown_regions):
            rest = clusters[len(shown_regions):]
            L.append(f"- {len(rest)} smaller regions: " + ", ".join(_short(c.get("label") or "", 30) for c in rest[:10]))
        loose = rank([n for n in tops if n.get("cluster", -1) == -1])
        if loose:
            L.append(f"### Not in a region ({len(loose)} notes)")
            L += [_fmt_note(n, frag_count, title_len) for n in loose[:per_region]]
            if len(loose) > per_region:
                L.append(f"- and {len(loose) - per_region} more")
        L.append("")
        if topics and topics.get("topics"):
            L.append("## Topics")
            for t in sorted(topics["topics"], key=lambda t: (-len(t.get("ids") or []), str(t.get("name")))):
                ids = [i for i in t.get("ids") or [] if i in nodes]
                head = rank([nodes[i] for i in ids])[:3]
                L.append(f"- {_short(str(t.get('name')), 40)} ({len(ids)}): " + ", ".join(f"[[{n['id']}]]" for n in head))
            L.append("")
        recent = sorted((full[i] for i in full if i in nodes and nodes[i]["type"] != "fragment"),
                        key=lambda n: (n.get("updated") or "", n["id"]), reverse=True)[:recent_n]
        if recent:
            L.append("## Recently added or changed")
            for n in recent:
                L.append(f"- [[{n['id']}]] {_short(n['title'], title_len)} ({(n.get('updated') or '')[:10]})")
            L.append("")
        queue = [i for i in (topics or {}).get("queue") or [] if i in nodes]
        if queue:
            L.append("## Reading queue")
            L += [f"- [[{i}]] {_short(nodes[i]['title'], title_len)}" for i in queue[:recent_n]]
            if len(queue) > recent_n:
                L.append(f"- and {len(queue) - recent_n} more")
            L.append("")
        L.append("## Where things are")
        L.append(f"- Papers with a PDF (full text, page-cited): {len(with_pdf)} of {len(papers)}.")
        no_pdf = rank([n for n in papers if not n.get("has_pdf")])
        if no_pdf:
            L.append("- Abstract only (no PDF): " + ", ".join(f"[[{n['id']}]]" for n in no_pdf[:8])
                     + (f" and {len(no_pdf) - 8} more" if len(no_pdf) > 8 else ""))
        most = sorted(frag_count.items(), key=lambda kv: (-kv[1], kv[0]))[:6]
        if most:
            L.append("- Most fragments: " + ", ".join(f"[[{i}]] ({c})" for i, c in most if i in nodes))
        summarised = [n for n in tops if n["id"] in full and (full[n["id"]].get("summary") or "").strip()]
        L.append(f"- Notes with your own summary: {len(summarised)}.")
        return "\n".join(L).rstrip() + "\n"

    for per, tl, rn, extra in ((6, 80, 8, True), (5, 70, 6, False), (4, 60, 5, False), (3, 50, 4, False),
                               (2, 44, 3, False), (1, 40, 3, False)):
        out = render(per, tl, rn, extra)
        if len(out.encode()) <= max_bytes:
            return out
    cut = out.encode()[:max_bytes - 60].decode("utf-8", "ignore")
    return cut[:cut.rfind("\n")] + "\n- (map truncated to stay small)\n"


def library_key(signature: str, engagement: dict, topics: dict | None) -> str:
    h = hashlib.sha1(signature.encode())
    h.update(json.dumps(engagement, sort_keys=True).encode())
    h.update(json.dumps(topics or {}, sort_keys=True, default=str).encode())
    return h.hexdigest()


def topics_snapshot(store, notes: list[dict]) -> dict | None:
    """Topics and the reading queue, if the topics feature (app/topics.py) exists. Guarded: any
    failure or a missing module gives None (or what the notes' own frontmatter says)."""
    try:
        from . import topics as _topics  # optional (topics + reading status feature)
    except Exception:
        _topics = None
    if _topics is not None:
        try:
            rows = []
            for t in _topics.list_topics(store):
                try:
                    members = list(_topics.get_topic(store, t["slug"]).get("members") or [])
                except Exception:
                    members = []
                rows.append({"name": t.get("name") or t["slug"], "slug": t["slug"], "ids": members})
            queue = []
            for st in ("reading", "to-read"):
                try:
                    queue += [x["id"] for x in _topics.papers_by_status(store, st)]
                except Exception:
                    pass
            if rows or queue:
                return {"topics": rows, "queue": queue}
        except Exception as e:
            print(f"[research_brain] topics snapshot failed: {e!r}")
    # fallback: frontmatter fields `topics` (list) and `reading` / `reading_status` / `status`
    by_topic: dict[str, list[str]] = {}
    queue = []
    for n in notes:
        ex = n.get("_extra") or {}
        ts = ex.get("topics") or ex.get("topic") or []
        if isinstance(ts, str):
            ts = [ts]
        for t in ts if isinstance(ts, list) else []:
            by_topic.setdefault(str(t), []).append(n["id"])
        st = str(n.get("status") or ex.get("reading_status") or ex.get("reading") or ex.get("status") or "").lower()
        if st in ("to-read", "to read", "toread", "queued", "queue", "reading", "unread"):
            queue.append(n["id"])
    if not by_topic and not queue:
        return None
    return {"topics": [{"name": k, "ids": sorted(v)} for k, v in sorted(by_topic.items())], "queue": sorted(queue)}
